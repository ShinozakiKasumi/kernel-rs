//! IDT: 48 vectors (0..31 exceptions, 32 timer, 33 keyboard, 44 mouse) plus
//! the int 0x80 system call gate. Stubs live in `asm.rs` (global_asm).

use core::arch::asm;
use core::cell::UnsafeCell;

/// Full CPU state at interrupt entry, pushed by `isr_common`.
/// Stack order at hand-off: r15 lowest ... rax, vector, err, rip, cs,
/// rflags, rsp, ss (user rsp/ss present only from user mode).
#[repr(C)]
#[derive(Clone, Copy)]
pub struct IrqFrame {
    pub r15: u64,
    pub r14: u64,
    pub r13: u64,
    pub r12: u64,
    pub r11: u64,
    pub r10: u64,
    pub r9: u64,
    pub r8: u64,
    pub rbp: u64,
    pub rdi: u64,
    pub rsi: u64,
    pub rdx: u64,
    pub rcx: u64,
    pub rbx: u64,
    pub rax: u64,
    pub vector: u64,
    pub err: u64,
    pub rip: u64,
    pub cs: u64,
    pub rflags: u64,
    pub rsp: u64,
    pub ss: u64,
}

const IDT_ENTRIES: usize = 129;

#[repr(C, packed)]
#[derive(Clone, Copy)]
struct IdtEntry {
    off_low: u16,
    sel: u16,
    ist: u8,
    flags: u8,
    off_mid: u16,
    off_high: u32,
    zero: u32,
}

struct IdtCell(UnsafeCell<[IdtEntry; IDT_ENTRIES]>);
unsafe impl Sync for IdtCell {}

static IDT: IdtCell = IdtCell(UnsafeCell::new(
    [IdtEntry {
        off_low: 0,
        sel: 0,
        ist: 0,
        flags: 0,
        off_mid: 0,
        off_high: 0,
        zero: 0,
    }; IDT_ENTRIES],
));

#[repr(C, packed)]
struct Idtr {
    limit: u16,
    base: u64,
}

const KERNEL_CS_SEL: u16 = 0x08;
const GATE_INT: u8 = 0x8E; // present, DPL0, 64-bit interrupt gate

fn idt_set(n: usize, handler: usize, flags: u8) {
    let addr = handler as u64;
    unsafe {
        (*IDT.0.get())[n] = IdtEntry {
            off_low: (addr & 0xFFFF) as u16,
            sel: KERNEL_CS_SEL,
            ist: 0,
            flags,
            off_mid: ((addr >> 16) & 0xFFFF) as u16,
            off_high: (addr >> 32) as u32,
            zero: 0,
        };
    }
}

extern "C" {
    /// One entry per vector 0..=47, generated by global_asm in asm.rs.
    static isr_stub_table: [usize; 48];
    fn isr_stub_128();
}

const IRQ_TIMER: u64 = 32;
const IRQ_KEYBOARD: u64 = 33;
const IRQ_MOUSE: u64 = 44;

