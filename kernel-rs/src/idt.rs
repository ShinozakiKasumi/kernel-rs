pub static mut TIMER_TICKS: u64 = 0;
/// Flipped once the scheduler is initialised.
pub static mut SCHED_ENABLED: bool = false;

fn on_timer(f: &mut IrqFrame) {
    unsafe {
        TIMER_TICKS += 1;
        if TIMER_TICKS % 100 == 0 {
            crate::klog_info!(
                "timer: {} ticks (~{}s)",
                TIMER_TICKS,
                TIMER_TICKS / 100
            );
        }
        if SCHED_ENABLED {
            crate::sched::sched_tick(f);
        }
    }
}

pub fn timer_ticks() -> u64 {
    unsafe { TIMER_TICKS }
}

fn on_keyboard() {
    let sc = crate::io::inb(0x60);
    crate::kbd::kbd_on_scancode(sc);
}

#[no_mangle]
extern "C" fn isr_handler(f: &mut IrqFrame) {
    if f.vector == 0x80 {
        crate::syscall::syscall_dispatch(f);
        return;
    }

    if f.vector >= 32 {
        match f.vector {
            IRQ_TIMER => {
                on_timer(f);
                crate::pic::eoi(0);
            }
            IRQ_KEYBOARD => {
                on_keyboard();
                crate::pic::eoi(1);
            }
            IRQ_MOUSE => {
                crate::gui::mouse::irq_handler();
                crate::pic::eoi(12);
            }
            v => {
                crate::klog_warn!("irq: stray vector {}", v);
                crate::pic::eoi((v - 32) as u8);
            }
        }
        return;
    }

    if f.vector == 3 {
        // #BP: recoverable test exception, just return
        crate::klog_info!("int3: handled at rip={:#x} (resuming)", f.rip);
        return;
    }

    crate::klog_err!(
        "EXCEPTION {}: {} err={:#x}",
        f.vector,
        EXC_NAMES[f.vector as usize],
        f.err
    );
    if f.vector == 14 {
        let cr2: u64;
        unsafe { asm!("mov {}, cr2", out(reg) cr2, options(nomem, nostack, preserves_flags)) };
        crate::klog!("  cr2={:#x}\n", cr2);
    }
    crate::klog!(
        "  rip={:#x} cs={:#x} rflags={:#x} rsp={:#x}\n",
        f.rip,
        f.cs,
        f.rflags,
        f.rsp
    );
    crate::klog!(
        "  rax={:#x} rbx={:#x} rcx={:#x} rdx={:#x}\n",
        f.rax,
        f.rbx,
        f.rcx,
        f.rdx
    );
    crate::klog!("  rsi={:#x} rdi={:#x} rbp={:#x}\n", f.rsi, f.rdi, f.rbp);

    crate::io::cli();
    loop {
        crate::io::hlt();
    }
}

pub fn init() {
    unsafe {
        for i in 0..48usize {
            idt_set(i, isr_stub_table[i], GATE_INT);
        }
    }

    idt_set(0x80, isr_stub_128 as usize, 0xEE); // present, DPL=3, interrupt gate

    let idtr = Idtr {
        limit: (core::mem::size_of::<[IdtEntry; IDT_ENTRIES]>() - 1) as u16,
        base: unsafe { (*IDT.0.get()).as_ptr() as u64 },
    };
    unsafe {
        asm!("lidt [{}]", in(reg) &idtr, options(nostack));
    }

    crate::pic::init();
    crate::pic::unmask(0); // PIT timer
    crate::pic::unmask(1); // keyboard

    crate::klog_info!(
        "idt: {} vectors loaded, PIC remapped, IRQ0/IRQ1 unmasked",
        IDT_ENTRIES
    );
}

pub fn enable() {
    crate::io::sti();
    crate::klog_info!(
        "interrupts enabled (ticks so far: {})",
        timer_ticks()
    );
}
